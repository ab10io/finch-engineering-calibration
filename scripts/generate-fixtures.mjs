for (const project of projects) {
  const fixture = fixtureBySlug.get(project.slug)
  if (!fixture) throw new Error(`Missing fixture metadata for ${project.slug}`)
  const projectRoot = resolve(root, 'fixtures', project.slug)
  if (!projectRoot.startsWith(resolve(root, 'fixtures') + '/')) throw new Error('Unsafe fixture path')
  await rm(projectRoot, { recursive: true, force: true })
  const files = {
    'README.md': readme(project),
    'docs/architecture.md': architecture(project),
    'docs/decisions.md': decisions(project),
    'docs/security.md': security(project),
    'docs/testing.md': testing(project),
    [project.sourcePath]: project.source,
    [project.manifestName || 'package.json']: project.manifest || defaultManifest(project),
    ...(project.testSource ? { [project.testPath]: project.testSource } : {}),
    ...(project.license ? { LICENSE: licenseText } : {}),
    ...(project.extras || {}),
  }
  for (const [relative, contents] of Object.entries(files)) {
    const target = resolve(projectRoot, relative)
    if (!target.startsWith(projectRoot + '/')) throw new Error('Unsafe generated path')
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, contents)
  }
  const submissionPath = resolve(root, 'calibration', 'submissions', `${project.slug}.json`)
  await mkdir(dirname(submissionPath), { recursive: true })
  await writeFile(submissionPath, JSON.stringify(submission(project, fixture), null, 2) + '\n')
}

process.stdout.write(`Generated ${projects.length} synthetic calibration fixtures.\n`)
